"""Build the final results sheet from the frozen-configuration runs (no number is typed by hand).

    python scripts/build_results.py --colab runs/colab3 [--local runs/final] [--demo runs/demo/results.json]

Inputs
  --local   component evaluations run on the final code (summarization, retrieval, sliding window)
  --colab   the unzipped Colab results folder; its ``final/`` subfolder holds the one-time test runs
  --demo    the coding-session demo result
  --before  the earlier full-LoCoMo run (old RAG read path), used for a before/after on the SAME
            test conversations

Outputs (``results/``)
  RESULTS.md              one table per component: claim number, baseline, 95% CI where computable
  final/<name>.json       copies of every summary used, so the sheet can be audited
Anything missing is shown as "pending" instead of failing.
"""

from __future__ import annotations

import argparse
import json
import shutil
import statistics
from pathlib import Path

import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "packages")]

from eval.metrics import cluster_bootstrap_ci  # noqa: E402
STRATS = ["sliding_window", "summarization", "rag", "hybrid", "adaptive"]
LABEL = {"sliding_window": "always sliding window", "summarization": "always summarization", "rag": "always RAG",
         "hybrid": "always hybrid", "adaptive": "**adaptive (CEAI)**"}


def load(path: Path):
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return None


def rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def f(x, nd=3) -> str:
    return "pending" if x is None else f"{x:.{nd}f}"


def ci(rs: list[dict], stat, group: str) -> str:
    if not rs:
        return ""
    c = cluster_bootstrap_ci(rs, stat, group_key=group, n_boot=2000)
    return f"{c['estimate']:.3f} [{c['ci_low']:.3f}, {c['ci_high']:.3f}]"


def hit_rate(key: str, s: str):
    return lambda rs: sum(bool(r[s][key]) for r in rs) / len(rs)


def delta(key: str, a: str, b: str):
    return lambda rs: sum(bool(r[a][key]) - bool(r[b][key]) for r in rs) / len(rs)


def test_conv_ids() -> set[str]:
    from eval.locomo.loader import load as load_locomo

    return {c.sample_id for i, c in enumerate(load_locomo()) if i % 2 == 1}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--colab", default=None)
    ap.add_argument("--local", default="runs/final")
    ap.add_argument("--demo", default="runs/demo/results.json")
    ap.add_argument("--before", default="eval/locomo/results_no_nli/questions.jsonl")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    out = ROOT / a.out
    (out / "final").mkdir(parents=True, exist_ok=True)
    local = ROOT / a.local
    final = (ROOT / a.colab / "final") if a.colab else None
    used: dict[str, Path] = {}
    md: list[str] = ["# CEAI results (frozen configuration)", "",
                     "Generated by `scripts/build_results.py` from the `summary.json` files listed at the end. "
                     "Test splits were run once, after the configuration was frozen on dev data (CLAUDE.md §12.4). "
                     "Brackets are 95% bootstrap intervals resampling whole conversations (LoCoMo) or items (LoCoMo-Plus).", ""]

    # ------------------------------------------------------------------ demo
    demo = load(ROOT / a.demo)
    md += ["## Integration: coding-session demo (deterministic, no judge)", ""]
    if demo:
        used["demo"] = ROOT / a.demo
        traps = list(next(iter(demo["results"].values())).keys())
        md += ["| strategy | " + " | ".join(traps) + " | score |", "|---|" + "---|" * (len(traps) + 1)]
        for s, r in demo["results"].items():
            cells = ["CAUGHT" if r[t]["caught"] else "MISSED" for t in traps]
            name = "**adaptive (CEAI)**" if s == "adaptive" else s.replace("_", " ")
            md.append(f"| {name} | " + " | ".join(cells) + f" | {sum(r[t]['caught'] for t in traps)}/{len(traps)} |")
    else:
        md.append("pending")
    md.append("")

    # ------------------------------------------------------------------ controller (headline)
    md += ["## Component 4: ASSE controller (headline claim, §6.1)", ""]
    for split in ("test", "val"):
        s = load(final / "controller" / split / "summary.json") if final else None
        if not s:
            md.append(f"Synthetic strategy-switch set, {split}: pending")
            continue
        used[f"controller_{split}"] = final / "controller" / split / "summary.json"
        e = s["evidence_hit_rate"]
        best = s.get("best_single_fixed_baseline")
        md += [f"**Synthetic strategy-switch conversations, {split} split** ({s['n_conversations']} conversations, {s['n_probes']} probes, budget {s['budget_tokens']})", "",
               "| strategy | evidence hit [95% CI] | mean context tokens |", "|---|---|---|"]
        for st in STRATS:
            v = e[st]
            md.append(f"| {LABEL[st]} | {v['estimate']:.3f} [{v['ci_low']:.3f}, {v['ci_high']:.3f}] | {s['mean_context_tokens'][st]:.0f} |")
        md.append("")
        for k, v in s.get("differences", {}).items():
            md.append(f"- {k}: **{v['estimate']:+.3f}** [{v['ci_low']:+.3f}, {v['ci_high']:+.3f}]")
        sel = s["selection"]
        md += [f"- strategy-selection macro-F1: {sel['adaptive_macro_f1']['estimate']:.3f} "
               f"[{sel['adaptive_macro_f1']['ci_low']:.3f}, {sel['adaptive_macro_f1']['ci_high']:.3f}] "
               f"(majority baseline {sel['majority_macro_f1']:.3f}, random {sel['random_macro_f1_mean_of_20']:.3f}); "
               f"acceptable-choice accuracy {sel['adaptive_acceptable_choice_accuracy']['estimate']:.3f}", ""]
        if split == "test":
            break  # val is shown only if test is missing

    # ------------------------------------------------------------------ LoCoMo + RAG
    md += ["## LoCoMo test split (primary benchmark) and Component 3: RAG", ""]
    loc = load(final / "locomo" / "summary.json") if final else None
    loc_rows = rows(final / "locomo" / "questions.jsonl") if final else []
    if loc:
        used["locomo_test"] = final / "locomo" / "summary.json"
        md += [f"Evidence reaching the context, {loc['n_questions']} questions, {loc['config']['conversations']} test conversations, budget {loc['config']['budget']} tokens.", "",
               "| strategy | evidence hit [95% CI] | answer string in context |", "|---|---|---|"]
        for st in STRATS:
            md.append(f"| {LABEL[st]} | {ci(loc_rows, hit_rate('hit', st), 'conv') or f(loc['strategies'][st]['evidence_hit_rate'])} | "
                      f"{f(loc['strategies'][st].get('answer_in_context'))} |")
        md += ["", f"- adaptive − best single fixed ({loc['best_fixed_baseline']}): {ci(loc_rows, delta('hit', 'adaptive', loc['best_fixed_baseline']), 'conv')}",
               f"- adaptive − always hybrid: {ci(loc_rows, delta('hit', 'adaptive', 'hybrid'), 'conv')}"]
        before = [r for r in rows(ROOT / a.before) if r["conv"] in test_conv_ids()]
        if before:
            b = sum(r["rag"]["hit"] for r in before) / len(before)
            md.append(f"- **RAG read path, before → after on the same test conversations:** {b:.3f} → "
                      f"{loc['strategies']['rag']['evidence_hit_rate']:.3f} (old: verbose headers, no reranker)")
        g = loc.get("granularity", {})
        if g:
            md += ["", "| chunking | NDCG@10 | recall@10 | words@10 | recall @ 400 words |", "|---|---|---|---|---|"]
            for m in ("turn", "segment", "adaptive"):
                v = g[m]
                md.append(f"| {m} | {v['ndcg@10']:.3f} | {v['recall@10']:.3f} | {v['tokens@10']:.0f} | {f(v.get('recall@word_budget'))} |")
    else:
        md.append("LoCoMo test: pending")
    md.append("")

    qa = load(final / "locomo_qa" / "summary.json") if final else None
    qa_rows = [r for r in rows(final / "locomo_qa" / "questions.jsonl") if "question" in r] if final else []
    md += ["### Answer accuracy (LLM answers from each strategy's context)", ""]
    if qa and qa_rows:
        used["locomo_qa_test"] = final / "locomo_qa" / "summary.json"
        md += [f"{len(qa_rows)} answerable random test questions; answers: {qa['config']['qa_llm']}; judge: {qa['config']['answer_judge']}. "
               "Judge scores are citable only after the human-agreement check (kappa ≥ 0.6).", "",
               "| strategy | judge score (1 / 0.5 / 0) [95% CI] | token-F1 |", "|---|---|---|"]
        for st in STRATS:
            js = [r for r in qa_rows if r[st].get("judge_score") is not None]
            md.append(f"| {LABEL[st]} | {ci(js, lambda rs, st=st: statistics.mean(r[st]['judge_score'] for r in rs), 'conv')} | "
                      f"{statistics.mean(r[st]['qa_f1'] for r in qa_rows):.3f} |")
    else:
        md.append("pending")
    md.append("")

    # ------------------------------------------------------------------ in-stream LoCoMo
    st_s = load(final / "locomo_stream" / "summary.json") if final else None
    st_rows = rows(final / "locomo_stream" / "questions.jsonl") if final else []
    md += ["## In-stream LoCoMo test (questions asked during the conversation)", ""]
    if st_s:
        used["locomo_stream_test"] = final / "locomo_stream" / "summary.json"
        md += ["| strategy | evidence hit [95% CI] | fresh | late |", "|---|---|---|---|"]
        for st in STRATS:
            md.append(f"| {LABEL[st]} | {ci(st_rows, hit_rate('hit', st), 'conv')} | {f(st_s['by_position']['fresh'].get(st))} | {f(st_s['by_position']['late'].get(st))} |")
        md += ["", f"- adaptive − best single fixed ({st_s['best_single_fixed']}): {ci(st_rows, delta('hit', 'adaptive', st_s['best_single_fixed']), 'conv')}",
               f"- adaptive − always hybrid: {ci(st_rows, delta('hit', 'adaptive', 'hybrid'), 'conv')}"]
    else:
        md.append("pending")
    md.append("")

    # ------------------------------------------------------------------ LoCoMo-Plus
    lp = load(final / "locomo_plus" / "summary.json") if final else None
    lp_rows = rows(final / "locomo_plus" / "items.jsonl") if final else []
    md += ["## LoCoMo-Plus test (supplementary; implicit cues)", ""]
    if lp:
        used["locomo_plus_test"] = final / "locomo_plus" / "summary.json"
        md += [f"{lp['n_items']} items, cue reached the context.", "", "| strategy | cue hit [95% CI] |", "|---|---|"]
        for st in STRATS + ["naive_summary"]:
            md.append(f"| {LABEL.get(st, st.replace('_', ' '))} | {ci(lp_rows, hit_rate('cue_hit', st), 'item')} |")
        md += ["", "Known weakness: see CLAUDE.md §12.3."]
    else:
        md.append("pending")
    md.append("")

    # ------------------------------------------------------------------ components
    md += ["## Component 2: hierarchical summarization (30 degradation-injected developer traces)", ""]
    sm = load(local / "summarization" / "summary.json")
    if sm:
        used["summarization"] = local / "summarization" / "summary.json"
        md += ["| system @ budget | loss ↓ | symbol retention ↑ | current-fact recall ↑ | stale-fact leakage ↓ |", "|---|---|---|---|---|"]
        for k, v in sm["results"].items():
            if k.endswith(("@500", "@1000")):
                md.append(f"| {k} | {v['loss_score']:.3f} | {v['symbol_retention_rate']:.2f} | {v['current_fact_recall']:.2f} | {v['stale_leak_rate']:.2f} |")
        md.append(f"\nLoss monitor sanity: Spearman(deleted fraction, live loss score) = {sm['loss_monitor_spearman_deletion_vs_loss']:.2f}")
    else:
        md.append("pending")
    md += ["", "## Component 3: RAG contradiction / staleness flags (184 templated pairs)", ""]
    rt = load(local / "retrieval" / "summary.json")
    if rt:
        used["retrieval"] = local / "retrieval" / "summary.json"
        v = rt["variants"]["bidirectional"]
        t = v["test_at_selected"]
        md.append(f"Threshold {v['threshold_selected_on_dev']} chosen on dev. **Test precision {t['precision']:.2f}, recall {t['recall']:.2f}, F1 {t['f1']:.2f}**; "
                  f"prefilter recall {v['prefilter_recall_of_positives']:.2f}; NLI calibration Brier {v['nli_calibration']['brier']:.3f}, ECE {v['nli_calibration']['ece_10bin']:.3f}.")
    else:
        md.append("pending")
    md += ["", "## Component 1: dynamic sliding window (40 topic-shift conversations, 360 probes)", ""]
    md += ["| budget | DSW recall | recency-only | fixed-token window | DSW vs recency win / tie / loss | equal-weights rank in ablation |", "|---|---|---|---|---|---|"]
    for name, b in (("sliding_window_b100", 100), ("sliding_window", 220)):
        sw = load(local / name / "summary.json")
        if sw:
            used[name] = local / name / "summary.json"
            w = sw["dsw_vs_recency_only"]
            rank = sw["ablation"].get("equal_weights_rank", "?")
            md.append(f"| {b} | {sw['dsw_equal_weights']['recall']:.3f} | {sw['recency_only_k8']['recall']:.3f} | {sw['fixed_token_window']['recall']:.3f} | "
                      f"{w['win']} / {w['tie']} / {w['loss']} | {rank} of {sw['ablation']['n_configs']} |")
        else:
            md.append(f"| {b} | pending | | | | |")

    md += ["", "## Sources", ""]
    for name, p in used.items():
        dst = out / "final" / f"{name}.json"
        shutil.copy(p, dst)
        md.append(f"- `{dst.relative_to(ROOT).as_posix()}` (from `{p.relative_to(ROOT).as_posix()}`)")
    (out / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {out / 'RESULTS.md'} ({len(used)} sources)")


if __name__ == "__main__":
    main()
